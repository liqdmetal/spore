#!/usr/bin/env bash
# push-detached.sh — push to origin in a session that outlives the caller.
#
# The pre-push hook runs the full gate suite, which is far longer than a chat or
# editor turn stays alive. Launching `git push` directly from one of those gets
# the push killed mid-run with nothing to say about why, so the push is handed to
# a one-shot Windows scheduled task: the task runs git in its own session, writes
# the whole transcript to a log, and then DELETES ITS OWN TASK as the last thing
# it does — whether the push succeeded, was refused, or crashed.
#
# The self-delete is the point, not a tidy-up. A task left registered stays armed
# at its placeholder clock time. If the push has already happened meanwhile, that
# slot fires a second run over an empty ref range, which the pre-push hook
# correctly refuses ("stdin carried no ref lines") — so a slot left armed turns a
# green push into something that reads like a failure minutes later. The wrapper
# therefore deletes the task on every exit path, last thing, after the push's own
# status is captured.
#
# There is no second layer: schtasks /Z ("delete after the final run") is refused
# unless the task carries an EndBoundary, and an end time short enough to be safe
# would terminate the task mid-gates and take the push with it. So a wrapper that
# is killed outright leaves the task registered — it will not re-fire on its own
# (a ONCE task has one slot), but the guard below refuses to arm another until it
# is deleted, and says how.
#
#	scripts/push-detached.sh [-r REMOTE] [-b BRANCH] [-w MINUTES]
#
# Defaults: origin, the current branch, and a start one minute out (schtasks
# cannot schedule finer than a minute). Refuses to arm a second task while one
# is registered, so two runs can never both be queued.

set -euo pipefail

REMOTE=origin
BRANCH=""
WAIT_MIN=1
TASK_NAME=SporePush

usage() { sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'; }

while [ $# -gt 0 ]; do
  case "$1" in
    -r|--remote) REMOTE=${2:?-r needs a remote}; shift 2 ;;
    -b|--branch) BRANCH=${2:?-b needs a branch}; shift 2 ;;
    -w|--wait)   WAIT_MIN=${2:?-w needs minutes}; shift 2 ;;
    -h|--help)   usage; exit 0 ;;
    *) echo "push-detached: unknown argument: $1" >&2; usage >&2; exit 2 ;;
  esac
done

ROOT=$(git rev-parse --show-toplevel)
cd "$ROOT"
BRANCH=${BRANCH:-$(git rev-parse --abbrev-ref HEAD)}
SHA=$(git rev-parse --short HEAD)

STATE_DIR="$ROOT/.push-detached"
WRAPPER="$STATE_DIR/run.bat"
LOG="$STATE_DIR/push.log"

# ---- one task at a time ----------------------------------------------------
# A registered task is a queued push. Arming another would let two runs race for
# the same ref, and the loser's empty-range refusal is indistinguishable from a
# real failure in the log.
if schtasks //Query //TN "$TASK_NAME" >/dev/null 2>&1; then
  cat >&2 <<EOF
push-detached: a "$TASK_NAME" task is already registered — refusing to arm a second one.

  Check it:    schtasks /Query /TN $TASK_NAME /V /FO LIST
  Read it:     cat "$LOG"
  Cancel it:   schtasks /Delete /TN $TASK_NAME /F
EOF
  exit 1
fi

mkdir -p "$STATE_DIR"

# Batch speaks backslash paths; git bash hands out forward slashes, and `cd /d`
# on a forward-slash path is not something to rely on when the whole point is
# that the push must run in the repo.
win_path() { cygpath -w "$1" 2>/dev/null || printf '%s' "$1" | sed 's#/#\\#g'; }
ROOT_WIN=$(win_path "$ROOT")
WRAPPER_WIN=$(win_path "$WRAPPER")
LOG_WIN=$(win_path "$LOG")

# ---- the wrapper -----------------------------------------------------------
# Batch, because schtasks runs the action without a shell. The body is split so
# the task delete is reached on both the success and the failure path: the push's
# status is captured first, the task is dropped next, and only then is that status
# returned. A failing delete cannot mask a failing push, and a failing push cannot
# skip the delete.
cat > "$WRAPPER" <<EOF
@echo off
rem Generated by scripts/push-detached.sh — one-shot push, deletes its own task.
setlocal
cd /d "$ROOT_WIN"
call :do_push
set "RC=%ERRORLEVEL%"
call :drop_task
endlocal & exit /b %RC%

:do_push
rem No "->" in these echoes: cmd reads ">" as a redirect, so an arrow here sends
rem the banner into a file named after the remote and leaves the log silent.
echo ==== push $SHA $BRANCH to $REMOTE started %DATE% %TIME% ====
git push --porcelain $REMOTE $BRANCH 2>&1
set "GRC=%ERRORLEVEL%"
echo ==== push exited %GRC% at %DATE% %TIME% ====
exit /b %GRC%

:drop_task
schtasks /Delete /TN "$TASK_NAME" /F 2>&1
echo ==== task $TASK_NAME deleted at %DATE% %TIME% ====
exit /b 0
EOF
# The wrapper's own output goes to the log; the task must not open a console.
cat > "$STATE_DIR/entry.bat" <<EOF
@echo off
call "$WRAPPER_WIN" >> "$LOG_WIN" 2>&1
exit /b %ERRORLEVEL%
EOF

: > "$LOG"

# ---- register --------------------------------------------------------------
START_AT=$(date -d "+${WAIT_MIN} minute" +%H:%M 2>/dev/null || date -v+"${WAIT_MIN}"M +%H:%M)
ENTRY_WIN=$(win_path "$STATE_DIR/entry.bat")
if ! schtasks //Create //TN "$TASK_NAME" //TR "\"$ENTRY_WIN\"" \
      //SC ONCE //ST "$START_AT" //F >/dev/null; then
  echo "push-detached: could not register the $TASK_NAME task" >&2
  exit 1
fi

if ! schtasks //Query //TN "$TASK_NAME" >/dev/null 2>&1; then
  echo "push-detached: registered $TASK_NAME but cannot query it back" >&2
  exit 1
fi

cat <<EOF
push-detached: armed $TASK_NAME for $START_AT (push $SHA $BRANCH -> $REMOTE)
  gates run inside the hook and take ~16 min; the task deletes itself when done.
  watch:   tail -f "$LOG"
  done:    grep -n "push exited\\|deleted" "$LOG"
  confirm: git fetch -q $REMOTE && git rev-parse $BRANCH $REMOTE/$BRANCH
EOF
