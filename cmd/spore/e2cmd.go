// msgE2 is deliberately separate from legacy msg: it has no one-shot
// fallback and never accepts plaintext as a command-line flag (argv is
// visible to shell history, `ps`, and crash/monitoring reports). Bundles can
// be supplied explicitly (-bundle) or fetched from a mailbox's /prekey
// endpoint (-bundle-url); either way, EstablishInitiator still verifies the
// bundle's SPK_sig against -pinned-sig, so discovery is a transport
// convenience only and never substitutes for out-of-band trust.
func msgE2(args []string) {
	if len(args) == 0 {
		fmt.Fprintln(os.Stderr, "usage: spore msg send-e2|recv-e2 [flags]")
		return
	}
	switch args[0] {
	case "send-e2":
		msgSendE2(args[1:])
	case "recv-e2":
		msgRecvE2(args[1:])
	case "reply-e2":
		msgReplyE2(args[1:])
	case "forward-e2":
		msgForwardE2(args[1:])
	case "sessions":
		msgSessions(args[1:])
	case "prekeygen":
		msgPrekeygen(args[1:])
	case "compose":
		msgCompose(args[1:])
	case "flush":
		msgFlush(args[1:])
	case "mail":
		msgMail(args[1:])
	case "invoice":
		msgInvoiceE2(args[1:])
	case "pay":
		msgPayE2(args[1:])
	default:
		fmt.Fprintln(os.Stderr, "msg: unknown e2 subcommand")
	}
}

// e2Store builds the off-chain body store from a -store URL. Two schemes:
//
//	http(s)://host    -> HTTPStore (your mailbox, or a paid Model-B operator)
//	nostr://r1,r2,r3  -> NostrStore: bodies live on a public relay commons
//
// The nostr:// form is the NO-SERVERS endgame: nobody operates a store for
// you, and any subset of the relays can serve a body by content address.
//
// nostr:// needs a signing key, and it must be a DEDICATED one — publishing
// bodies is linkable by pubkey, so reusing the ratchet identity or a chain key
// would let a relay tie storage activity to messaging identity. -store-key
// (a 32-byte hex file, generated by `spore init`) supplies it; it is required
// for the nostr scheme and ignored for http.
func e2Store(url, token, keyFile string) (ratchetwire.BodyStore, error) {
	if url == "" {
		return nil, errors.New("-store is required (E2 never uses a local-only implicit store)")
	}
	if rest, ok := strings.CutPrefix(url, "nostr://"); ok {
		var relays []string
		for _, r := range strings.Split(rest, ",") {
			if r = strings.TrimSpace(r); r != "" {
				if !strings.HasPrefix(r, "wss://") && !strings.HasPrefix(r, "ws://") {
					r = "wss://" + r
				}
				relays = append(relays, r)
			}
		}
		if len(relays) == 0 {
			return nil, errors.New("-store nostr:// requires at least one relay (e.g. -store nostr://relay.damus.io,nos.lol)")
		}
		if keyFile == "" {
			return nil, errors.New("-store nostr:// requires -store-key (a DEDICATED body-store signing key file; `spore init` writes one at store.key — do not reuse your identity or chain key, publishing is linkable by pubkey)")
		}
		k, err := readHexFile(keyFile, 32)
		if err != nil {
			return nil, err
		}
		// Index next to the key so Delete/Reap survive restarts. Without it
		// we could still Get, but Reap would have nothing to iterate — i.e.
		// bodies would never be cleaned up from the commons.
		indexPath := ""
		if dir := filepath.Dir(keyFile); dir != "" && dir != "." {
			indexPath = filepath.Join(dir, "nostrstore-index.json")
		}
		return nostr.NewNostrStore(nostr.NostrStoreConfig{
			PrivateKey: hex.EncodeToString(k),
			Relays:     relays,
			IndexPath:  indexPath,
		})
	}
	return store.NewHTTPStoreWithToken(url, token)
}
func e2Carrier(fs *flag.FlagSet) (ratchetwire.ChainCarrier, error) {
	value := func(name string) string {
		if f := fs.Lookup(name); f != nil {
			return f.Value.String()
		}
		return ""
	}
	privateKey := value("private-key")
	if path := value("private-key-file"); path != "" {
		b, err := os.ReadFile(path)
		if err != nil {
			return ratchetwire.ChainCarrier{}, err
		}
		privateKey = strings.TrimSpace(string(b))
	}
	var relays []string
	if raw := value("relays"); raw != "" {
		for _, r := range strings.Split(raw, ",") {
			if r = strings.TrimSpace(r); r != "" {
				relays = append(relays, r)
			}
		}
	}
	cfg := backend.ChainConfig{Type: value("chain"), RPC: value("rpc"), Login: value("rpc-login"), From: value("from"), KeyFile: value("keyfile"), ProgramID: value("program"), PrivateKey: privateKey, Network: value("network"), BaseURL: value("base-url"), Address: value("address"), Name: value("chain-id"), PostPath: value("post-path"), ListPath: value("list-path"), HeightPath: value("height-path"), MessageField: value("message-field"), RecipientField: value("recipient-field"), DeliveryGuaranteed: value("delivery-guaranteed") == "true", Relays: relays}
	c, err := backend.Build(context.Background(), cfg)
	if err != nil {
		return ratchetwire.ChainCarrier{}, err
	}
	var codec ratchetwire.ChainPayloadCodec
	switch strings.ToLower(c.Name()) {
	case "dero":
		codec = ratchetwire.DeroChainCodec{}
	case "evm", "solana":
		codec = ratchetwire.JSONCodec{}
	case "nostr", "bitcoin", "cosmos", "ton":
		codec = ratchetwire.CanonicalChainCodec{}
	default:
		return ratchetwire.ChainCarrier{}, fmt.Errorf("E2 pointer carrier unsupported on %s; refusing downgrade", c.Name())
	}
	return ratchetwire.ChainCarrier{Chain: c, Codec: codec}, nil
}
func readHexFile(path string, n int) ([]byte, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	x, err := hex.DecodeString(strings.TrimSpace(string(b)))
	if err != nil || (n > 0 && len(x) != n) {
		return nil, fmt.Errorf("%s must contain %d-byte hex", path, n)
	}
	return x, nil
}
func readBundle(path string) (*ratchet.SPKBundle, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var out ratchet.SPKBundle
	if err := json.Unmarshal(b, &out); err != nil {
		return nil, wrongBundleFileError(path, b, err)
	}
	if err := validateBundleStruct(&out); err != nil {
		// A structurally-empty bundle is almost always the wrong FILE (an
		// identity card, a batch, or unrelated JSON), so diagnose the file
		// rather than only reporting the zero fields.
		return nil, wrongBundleFileError(path, b, err)
	}
	return &out, nil
}

// validateBundleStruct is the shared structural gate for a decoded SPKBundle,
// used by BOTH the file (-bundle) and discovery (-bundle-url) paths.
//
// json.Unmarshal ignores unknown fields, so `{}` or `{"bundle":{}}` parses
// cleanly into an all-zero SPKBundle. Without this check a zero bundle would
// reach the X3DH handshake and fail later as a confusing signature error
// instead of "you pointed at the wrong file".
func validateBundleStruct(b *ratchet.SPKBundle) error {
	if b == nil {
		return errors.New("nil bundle")
	}
	if b.IKPub == [32]byte{} || b.SPKPub == [32]byte{} || b.SPKSig == [64]byte{} {
		return errors.New("bundle has no identity/signed-prekey material (all-zero fields)")
	}
	// OPKPub nil with a nonzero OPKID is inconsistent: degraded mode must
	// carry OPKID 0. Mirrors the mailbox's own bundle validation.
	if b.OPKPub != nil {
		if *b.OPKPub == [32]byte{} {
			return errors.New("bundle declares an OPK id but the OPK public key is zero")
		}
	} else if b.OPKID != 0 {
		return fmt.Errorf("bundle declares OPK id %d with no OPK public key", b.OPKID)
	}
	return nil
}

// wrongBundleFileError diagnoses the common ways -bundle gets handed the wrong
// file, naming the mistake and the fix rather than surfacing a raw Go type
// error that tells the user nothing.
func wrongBundleFileError(path string, b []byte, cause error) error {
	var probe struct {
		IKPub   string            `json:"ik_pub"`
		Bundles []json.RawMessage `json:"bundles"`
	}
	if json.Unmarshal(b, &probe) == nil {
		if len(probe.Bundles) > 0 {
			return fmt.Errorf("%s is a prekey BATCH (push it with `spore prekeybatch push`); -bundle wants a single SPKBundle, or use -bundle-url to fetch one from the recipient's mailbox", path)
		}
		if probe.IKPub != "" {
			return fmt.Errorf("%s is an identity CARD (ik_pub + pinned_sig), not a prekey bundle; -bundle wants a single SPKBundle. Share the card so your contact can pin you, and fetch THEIR bundle with -bundle-url http://THEIR-MAILBOX/prekey", path)
		}
	}
	return fmt.Errorf("%s is not a valid SPKBundle: %w", path, cause)
}

// fetchBundle discovers a recipient's public prekey bundle from a mailbox's
// GET /prekey endpoint. This is a transport convenience over -bundle FILE.json
// only: EstablishInitiator still verifies SPK_sig against the caller-supplied
// -pinned-sig, so a compromised or malicious mailbox can at worst withhold or
// serve a stale bundle (causing send-e2 to fail) — it cannot forge a bundle
// that passes signature pinning, and it never sees plaintext, ciphertext, or
// any private key material (this is a GET with no body).
func fetchBundle(ctx context.Context, url, token string) (*ratchet.SPKBundle, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return nil, err
	}
	if token != "" {
		req.Header.Set("Authorization", "Bearer "+token)
	}
	resp, err := (&http.Client{Timeout: 15 * time.Second}).Do(req)
	if err != nil {
		return nil, fmt.Errorf("bundle discovery: %w", err)
	}
	defer resp.Body.Close()
	if resp.StatusCode == http.StatusNotFound {
		return nil, errors.New("bundle discovery: recipient has not published a prekey bundle")
	}
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("bundle discovery: unexpected status %s", resp.Status)
	}
	var wire struct {
		Bundle ratchet.SPKBundle `json:"bundle"`
	}
	dec := json.NewDecoder(io.LimitReader(resp.Body, 16<<10))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&wire); err != nil {
		return nil, fmt.Errorf("bundle discovery: malformed response: %w", err)
	}
	// Same structural gate as readBundle: a mailbox returning {"bundle":{}}
	// (or a partial bundle) must not reach the X3DH handshake as a zero value.
	if err := validateBundleStruct(&wire.Bundle); err != nil {
		return nil, fmt.Errorf("bundle discovery from %s: %w", url, err)
	}
	return &wire.Bundle, nil
}

// readPlaintext resolves the message body without ever putting it on the
// command line: shell history, `ps`/process listings, and crash/monitoring
// tools all read argv. -msg-file reads a file (use /dev/stdin or a named
// pipe for scripting); with neither flag set, plaintext is read from stdin
// so it never appears as a process argument.
func readPlaintext(msgFile string) ([]byte, error) {
	if msgFile != "" {
		if msgFile == "-" {
			return readAllTrimNewline(os.Stdin)
		}
		b, err := os.ReadFile(msgFile)
		if err != nil {
			return nil, err
		}
		return trimTrailingNewline(b), nil
	}
	return readAllTrimNewline(os.Stdin)
}

func readAllTrimNewline(r io.Reader) ([]byte, error) {
	b, err := io.ReadAll(r)
	if err != nil {
		return nil, err
	}
	return trimTrailingNewline(b), nil
}

func trimTrailingNewline(b []byte) []byte {
	b = bytes.TrimSuffix(b, []byte("\n"))
	b = bytes.TrimSuffix(b, []byte("\r"))
	return b
}

